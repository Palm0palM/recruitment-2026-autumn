#!/usr/bin/env python3
"""Calibrate a V5 platform profile from ONLY its training session."""
import argparse
import json
import math
from pathlib import Path

import numpy as np
from scipy.optimize import nnls


def features(row):
    p, frames = row["params"], row["n_frames"]
    work = frames * p["n_fft"] * math.log2(p["n_fft"]) / 1e8
    # Empirical working-set pressure term. B16 scratch grows with n_fft;
    # the 32K/64K measurements resolve a slope change absent in the old grid.
    cache_work = work * max(0.0, p["n_fft"] / 16384.0 - 1.0)
    return [1.0, work, row["input_bytes"] / 1e6,
            frames * p["n_mels"] * 4 / 1e6, cache_work]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("input", type=Path)
    ap.add_argument("--gpu", choices=("cuda", "hip"), required=True)
    ap.add_argument("--header", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    rows = json.loads(args.input.read_text())
    X = np.array([features(r) for r in rows])
    yc = np.array([r["cpu_median"] for r in rows])
    yg = np.array([r[args.gpu + "_median"] for r in rows])
    cpu = nnls(X, yc)[0]
    gpu = nnls(X, yg)[0]
    predicted_cpu = X @ cpu <= X @ gpu
    truth_cpu = yc <= yg
    wrong = np.flatnonzero(predicted_cpu != truth_cpu)
    loo = []
    for i in range(len(rows)):
        mask = np.arange(len(rows)) != i
        c, g = nnls(X[mask], yc[mask])[0], nnls(X[mask], yg[mask])[0]
        if (X[i] @ c <= X[i] @ g) != truth_cpu[i]:
            loo.append(rows[i]["name"])
    result = dict(cpu=cpu.tolist(), gpu=gpu.tolist(), gpu_name=args.gpu,
                  features=["bias", "fft_work", "input_mb", "output_mb", "cache_work"],
                  correct=len(rows)-len(wrong), total=len(rows),
                  cpu_mae=float(np.mean(np.abs(X@cpu-yc))),
                  gpu_mae=float(np.mean(np.abs(X@gpu-yg))),
                  misclassified=[rows[i]["name"] for i in wrong],
                  loo_misclassified=loo, source=str(args.input))
    args.out.write_text(json.dumps(result, indent=2) + "\n")
    prefix = args.gpu.upper()
    lines = ["#pragma once", "// Generated by scripts/final_model.py; training session only."]
    for label, values in (("CPU", cpu), (prefix, gpu)):
        for term, value in zip(("CONST", "WORK", "INPUT", "OUTPUT", "CACHE"), values):
            macro = f"MELSPEC_MODEL_{label}_{term}"
            lines += [f"#ifndef {macro}", f"#define {macro} {value:.12g}", "#endif"]
    args.header.write_text("\n".join(lines) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
