#!/usr/bin/env bash
# Rootless ROCm 7.1 user space for the AMD Radeon AI PRO R9700 (gfx1201).
#
# Downloads Ubuntu/ROCm .deb files and extracts them into this worktree's tmp.
# It never installs packages system-wide, never uses sudo, and never modifies the
# shared Python environment. Kernel amdgpu/KFD support must already exist.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." && pwd)"
BASE="${AMD_ROCM_BASE:-$ROOT/tmp/amd-gpu}"
PKGS="$BASE/pkgs"
PREFIX="$BASE/root"
ENVFILE="$BASE/env.sh"
mkdir -p "$PKGS" "$PREFIX"

PACKAGES=(
  rocminfo libhsa-runtime64-1 libhsakmt1 librocm-core1
  rocm-smi librocm-smi64-7 libamd-smi26
  libamdhip64-7 libamdhip64-dev libamd-comgr3 rocm-device-libs-21
  hipcc clang-21 llvm-21 lld-21 clang-tools-21
  libclang-rt-21-dev libclang-common-21-dev libstdc++-16-dev
  libhipfft0 libhipfft-dev libhipfftw0
  librocfft0 librocfft-dev libhiprtc7
)

need_extract=0
[ -x "$PREFIX/usr/bin/hipcc" ] || need_extract=1
[ -f "$PREFIX/usr/include/hipfft/hipfft.h" ] || need_extract=1
[ -e "$PREFIX/usr/lib/x86_64-linux-gnu/libhipfft.so" ] || need_extract=1

if [ "$need_extract" -eq 1 ]; then
  echo "Downloading ROCm packages into $PKGS"
  (
    cd "$PKGS"
    apt download "${PACKAGES[@]}"
    for deb in ./*.deb; do
      dpkg-deb -x "$deb" "$PREFIX"
    done
    : > packages.txt
    for deb in ./*.deb; do
      printf '%s %s %s\n' \
        "$(dpkg-deb -f "$deb" Package)" \
        "$(dpkg-deb -f "$deb" Version)" \
        "$(basename "$deb")" >> packages.txt
    done
    sort -o packages.txt packages.txt
  )
else
  echo "Reuse extracted ROCm user space: $PREFIX"
fi

DEVICE_LIB="$PREFIX/usr/lib/llvm-21/lib/clang/21/amdgcn/bitcode"
for required in \
  "$PREFIX/usr/bin/hipcc" \
  "$PREFIX/usr/include/hip/hip_runtime.h" \
  "$PREFIX/usr/include/hipfft/hipfft.h" \
  "$PREFIX/usr/lib/x86_64-linux-gnu/libamdhip64.so" \
  "$PREFIX/usr/lib/x86_64-linux-gnu/libhipfft.so" \
  "$PREFIX/usr/lib/x86_64-linux-gnu/librocfft.so" \
  "$DEVICE_LIB"; do
  [ -e "$required" ] || { echo "Missing ROCm component: $required" >&2; exit 1; }
done

cat > "$ENVFILE" <<EOF
# Generated by scripts/setup_amd_rocm.sh. Source from project root:
#   source tmp/amd-gpu/env.sh
export ROCM_PREFIX="$PREFIX"
export ROCM_PATH="\$ROCM_PREFIX/usr"
export HIP_PATH="\$ROCM_PREFIX/usr"
export HIP_DEVICE_LIB_PATH="$DEVICE_LIB"
export HIPCC="\$ROCM_PREFIX/usr/bin/hipcc"
export HIP_ARCH="gfx1201"
export HIP_PLATFORM="amd"
export PATH="\$ROCM_PREFIX/usr/bin:\$ROCM_PREFIX/usr/lib/llvm-21/bin\${PATH:+:\$PATH}"
export LD_LIBRARY_PATH="\$ROCM_PREFIX/usr/lib/x86_64-linux-gnu\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export LIBRARY_PATH="\$ROCM_PREFIX/usr/lib/x86_64-linux-gnu\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
export CPATH="\$ROCM_PREFIX/usr/include/hipfft:\$ROCM_PREFIX/usr/include\${CPATH:+:\$CPATH}"
export CMAKE_PREFIX_PATH="\$ROCM_PREFIX/usr\${CMAKE_PREFIX_PATH:+:\$CMAKE_PREFIX_PATH}"
EOF
chmod +x "$ENVFILE"
echo "ROCm prefix: $PREFIX"
echo "Environment: source $ENVFILE"
echo "HIPCC=$PREFIX/usr/bin/hipcc"
echo "HIP_ARCH=gfx1201"
